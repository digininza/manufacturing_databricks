--
-- RULE OF THUMB USED ON THIS PROJECT
--   * Business logic that MANY consumers must agree on (OEE roll-up, scrap cost,
--     MTTR/MTBF) is defined ONCE, here in SQL: Power BI, Excel, finance SQL users and
--     data-science notebooks all get the same number.
--   * Small, pre-aggregated or "latest status" result sets -> DirectQuery on these views.
--   * Large, highly sliced, time-intelligence analysis -> Import semantic model on GOLD
--     star schema (powerbi/ project), NOT on these views.
